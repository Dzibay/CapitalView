/**
 * Категориальная палитра графиков — оттенки индиго и серые, фиксированный порядок слотов.
 * Проверена validate_palette.js на тёмном фоне #101115: соседние пары CVD ΔE ≥ 14.6,
 * normal ΔE ≥ 15.9, контраст с фоном ≥ 3:1. Несоседние пары различаются хуже, поэтому
 * цвет никогда не работает один: у плиток и сегментов есть подписи, легенда и зазоры 2px.
 * Цвет закреплён за сущностью (типом актива), а не за рангом.
 */
export const SERIES = ['#7381ff', '#b0b8ff', '#5060dc', '#c6cad6', '#8e93a5', '#5f6478', '#a08cf5', '#7a7f92']
export const OTHER = '#464a57'
/** нейтральная линия сравнения (вложено, база) */
export const NEUTRAL = '#8a8d99'

const TYPE_SLOT = {
  'Акции': 0,
  'Облигации': 1,
  'Фонды': 2,
  'Криптовалюта': 3,
  'Валюта': 4,
  'Драгоценные металлы': 5,
  'Вклады': 6,
  'Недвижимость': 7,
}

export function typeColor(type) {
  const i = TYPE_SLOT[type]
  return i == null ? OTHER : SERIES[i]
}

/** Тип, у которого нет своего слота, уходит в «Другое». */
export function typeGroup(type) {
  return TYPE_SLOT[type] == null ? 'Другое' : type
}

/** Выплаты: дивиденды — основной индиго, купоны — светлый, амортизация — серый. */
export const PAYOUT_COLORS = {
  dividends: SERIES[0],
  coupons: SERIES[1],
  amortizations: SERIES[4],
}
